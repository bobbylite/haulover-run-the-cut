// Weather presets: art direction (sun, sky, haze, water tints, grading) + physical sea state.
// Compass bearings: 0 = N, 90 = E, 180 = S, 270 = W. "from" = where it comes from.

export interface WeatherPreset {
  id: string;
  name: string;
  blurb: string;
  icon: 'sunset' | 'sun' | 'mist' | 'storm' | 'wind' | 'moon';
  danger: 1 | 2 | 3 | 4 | 5;
  /** Listed only by this game's menu (a place's own skies); unset = every game offers it. */
  exclusive?: string;

  // sun / moon
  sunAzimuth: number;
  sunElevation: number;
  sunColor: string;
  sunIntensity: number;
  night?: boolean;

  // sky
  skyHorizon: string;
  skyMid: string;
  skyZenith: string;
  cloudCover: number; // 0 clear .. 1 overcast
  cloudStorm: number; // 0 white .. 1 charcoal
  cloudLit: string;
  cloudShade: string;
  haze: number; // exponential fog density (1/m)
  hazeColor: string;

  // water
  waterDeep: string;
  waterShallow: string;
  waterGlow: string;
  foam: number; // foam eagerness 0..1.5

  // sea state
  windSpeed: number; // m/s
  windFrom: number;
  gust: number;
  swellHeight: number;
  swellFrom: number;
  swellLength: number;
  chopHeight: number;
  rain: number;
  lightning: number;

  // grading
  exposure: number;
  saturation: number;
  contrast: number;
  bloom: number;
  vignette: number;
  warmth: number; // +warm / -cool split tone
}

