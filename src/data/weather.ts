export const weatherById = (id: string): WeatherPreset =>
  WEATHER.find((w) => w.id === id) ?? (WEATHER[0] as WeatherPreset);

/**
 * The skies a game's menu offers. A game with skies of its own offers only those (Montauk's are all wind
 * against tide); the others share the common set.
 */
export const weatherFor = (game: string): WeatherPreset[] => {
  const own = WEATHER.filter((w) => w.exclusive === game);
  return own.length ? own : WEATHER.filter((w) => !w.exclusive);
};
